    private void procesarInicioSesion() {
        String correo = txtCorreo.getText().trim();
        String contrasena = new String(txtContrasena.getPassword()); 

        if (correo.isEmpty() || contrasena.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, completa todos los campos.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (correo.equals("admin@admin.com") && contrasena.equals("1234")) {
            VentanaPrincipal principal = new VentanaPrincipal();
            principal.setLocationRelativeTo(null);
            principal.setVisible(true);
            
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Correo o contraseña incorrectos.", "Error de acceso", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    private void procesarRegistroNuevoUsuario() {
        String correo = txtRegCorreo.getText().trim();
        String nuevaContrasena = new String(txtRegContrasena.getPassword());
        String contrasenaRep = new String(txtRegContrasenaRep.getPassword());

        if (correo.isEmpty() || nuevaContrasena.isEmpty() || contrasenaRep.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todos los campos de registro son obligatorios.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!nuevaContrasena.equals(contrasenaRep)) {
            JOptionPane.showMessageDialog(this, "Las contraseñas no coinciden. Por favor, verifícalas.", "Error de validación", JOptionPane.ERROR_MESSAGE);
            return;
        }

        JOptionPane.showMessageDialog(this, "¡Usuario " + correo + " registrado con éxito!");

        txtRegCorreo.setText("");
        txtRegContrasena.setText("");
        txtRegContrasenaRep.setText("");

        navegadorTarjetas.show(jpContenedorLogin, "jpTarjetaLogin");
    }

